/** Three-letter form for tight axes. */
export function monthShort(month: number, lang: Lang): string {
  return (MONTHS[lang][month] ?? '').slice(0, 3)
}

export function monthLabel(month: number, lang: Lang): string {
  return MONTHS[lang][month] ?? ''
}

