/** `en` is no longer offered in the toggle; it stays as the last-resort
 *  fallback for any key a translation happens to miss. */
const DICTS: Record<Lang, Dict> = { uz, uzc, ru }

const STORAGE_KEY = 'tailor.lang'

/** Uzbek is the shop's working language, so it wins over the browser locale;
 *  only an explicit pick from the header toggle changes it. */
function detect(): Lang {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved && (LANGS as readonly string[]).includes(saved)) return saved as Lang
  return 'uz'
}

let current: Lang = detect()
const listeners = new Set<() => void>()

function subscribe(fn: () => void) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

export function setLang(lang: Lang) {
  current = lang
  localStorage.setItem(STORAGE_KEY, lang)
  document.documentElement.lang = lang
  listeners.forEach((fn) => fn())
}

export function getLang(): Lang {
  return current
}

export function translate(key: string, lang: Lang = current): string {
  return DICTS[lang][key] ?? uz[key] ?? en[key] ?? key
}

/** Always day-first (dd/mm/yyyy). The shop reads dates that way in every
 *  language, and a US-configured tablet would otherwise print month-first. */
export function formatDate(ts: number | string): string {
  const d = typeof ts === 'string' ? new Date(ts + 'T00:00:00') : new Date(ts)
  if (Number.isNaN(d.getTime())) return ''
  const dd = String(d.getDate()).padStart(2, '0')
  const mm = String(d.getMonth() + 1).padStart(2, '0')
  return `${dd}/${mm}/${d.getFullYear()}`
}

export function useI18n() {
  const lang = useSyncExternalStore(subscribe, getLang, getLang)
  return {
    lang,
    setLang,
    t: (key: string) => translate(key, lang),
    formatDate: (ts: number | string) => formatDate(ts),
  }
}
